const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const base = process.env.TEST_URL || 'http://127.0.0.1:8766/'
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  try {
    for (const width of [390, 1280]) {
      const context = await browser.newContext({ viewport: { width, height: 800 } })
      const page = await context.newPage()
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(base)
      // 旧版的“进入过帮助页”记录不能冒充实际展开过使用建议。
      await page.evaluate(() => wx.setStorageSync('pblossom_faq_seen', '3.0.0'))
      await page.reload()
      const dots = page.locator('.tab-badge, .web-side-badge')
      assert(await dots.count() > 0)
      const help = page.locator(width < 900 ? '.tab[aria-label="常见问题"]' : '.web-sidebar [aria-label="常见问题"]')
      await help.click()
      await page.waitForTimeout(750)
      assert(await dots.count() > 0, '进入帮助页不消除红点')
      const usage = page.locator('.faq-item').first()
      assert.equal(await usage.locator('.faq-unread-dot').count(), 1)
      assert.equal(await usage.locator('.faq-title .faq-unread-dot').count(), 1, '红点在标题右侧')
      assert.equal(await usage.locator('.faq-unread-dot').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(250, 81, 81)')
      assert.notEqual(await usage.locator('.plus').evaluate(el => getComputedStyle(el, '::before').backgroundColor), 'rgb(250, 81, 81)', '加号保持原色')
      assert((await usage.locator('.faq-unread-dot').boundingBox()).width >= 9, '红点有足够可见尺寸')
      const alignment = await usage.evaluate(el => {
        const title = el.querySelector('.faq-title-text').getBoundingClientRect()
        const dot = el.querySelector('.faq-unread-dot').getBoundingClientRect()
        return Math.abs(title.top + title.height / 2 - dot.top - dot.height / 2)
      })
      assert(alignment < 0.5, '红点与标题文字中心对齐')
      await page.locator('.faq-head').nth(1).click()
      await page.waitForTimeout(500)
      assert(await dots.count() > 0, '展开其他问题不算已读')
      await usage.locator('.faq-head').click()
      await page.waitForTimeout(550)
      assert.equal(await usage.evaluate(el => el.classList.contains('faq-item-open')), true)
      assert.equal(await dots.count(), 0, '展开使用建议才消除红点')
      assert.equal(await usage.locator('.faq-unread-dot').count(), 0)
      assert.equal(await page.evaluate(() => wx.getStorageSync('pblossom_usage_seen')), '3.0.0')
      await usage.locator('.faq-head').click()
      await page.waitForTimeout(450)
      assert.equal(await usage.locator('.faq-unread-dot').count(), 0, '已读后收起不再出现红点')
      await page.reload()
      await help.click()
      await page.waitForTimeout(700)
      assert.equal(await dots.count(), 0, '重载后仍记住已读状态')
      assert.equal(await page.locator('.faq-unread-dot').count(), 0)
      assert.deepEqual(errors, [])
      console.log(`${width}px: 旧记录迁移、进入/其他问题不消点、展开已读及跨重载保存通过`)
      await context.close()
    }
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
